    for sid, title, lines in SCENES:
        sc = {"id": sid, "title": title, "lines": []}
        for lid, covers, sub in lines:
            say = to_say(sub)
            sc["lines"].append({"id": lid, "covers": covers, "sub": sub, "say": say, "say_parts": sentences(say)})

SECTION = "coder"
VERSION = "2026-11-02.1"
CARD = Path(__file__).resolve().parent / "rulebook" / "coder_card.md"
SVG_NS = "http://www.w3.org/2000/svg"
MAX_BYTES = 40_000
MAX_ELEMENTS = 400
MIN_SHAPES = 3
SHAPES = frozenset({"path", "rect", "circle", "ellipse", "line", "polyline", "polygon"})
ELEMENTS = SHAPES | {"svg", "g", "defs", "linearGradient", "radialGradient", "stop", "clipPath", "title", "desc"}
ATTRIBUTES = frozenset({
    "xmlns", "version", "viewBox", "width", "height", "preserveAspectRatio", "id", "transform", "d", "x", "y", "x1", "y1", "x2",
    "y2", "cx", "cy", "r", "rx", "ry", "fx", "fy", "points", "pathLength", "fill", "fill-opacity", "fill-rule", "stroke",
    "stroke-width", "stroke-opacity", "stroke-linecap", "stroke-linejoin", "stroke-dasharray", "stroke-dashoffset",
    "stroke-miterlimit", "opacity", "clip-path", "clip-rule", "clipPathUnits", "gradientUnits", "gradientTransform",
    "spreadMethod", "offset", "stop-color", "stop-opacity", "vector-effect"})
BLANK = {"none", "transparent", "white", "#fff", "#ffffff"}
URL_REF = re.compile(r"url\(\s*#([A-Za-z_][\w.-]{0,60})\s*\)")
BAD_VALUE = re.compile(r"javascript:|data:|https?:|//|expression\(|@import|<|url\((?!\s*#)", re.IGNORECASE)
SOURCE = CODER_SOURCE                     # the asset source the licence policy reads (generated_images): "bie_coder"
LICENCE = "CC0 1.0 (drawn by BIE's coder)"
LICENCE_URL = "https://creativecommons.org/publicdomain/zero/1.0/"
GENERATED_BY = "generated by BIE through the ChatGPT plan (BIE's coder, SVG code)"
AUTHOR = "BIE (Book Intelligence Engine)"
SCHEMA = obj({"name": S, "svg": S, "tags": arr(S), "alt": S})
# What the coder never draws (card rule 8; the licence policy; Navin's decisions): a person or a likeness, a name (a place, a
# brand, a person: a word with a capital letter), a map, a flag, a logo or an emblem.
PEOPLE = re.compile(r"\b(person|people|man|men|woman|women|boy|girl|child|children|face|portrait|selfie|photo|crowd|family|"
                    r"king|queen|emperor|sultan|minister|president|leader|governor)s?\b|व्यक्ति|आदमी|औरत|लोग|चेहरा|राजा|रानी",
                    re.IGNORECASE)
NEVER = re.compile(r"\b(map|maps|flag|flags|logo|logos|emblem|emblems|trademark|brand|border|boundary)\b|नक्शा|झंडा", re.IGNORECASE)
LIMIT = 150                               # drawings per run, most-used things first (run c: 139 would be drawn)


class CoderError(ValueError):
    pass


def card() -> str:
    return CARD.read_text(encoding="utf-8")


def _local(tag: str) -> tuple:
    if tag.startswith("{"):
        ns, _, name = tag[1:].partition("}")
        return ns, name
    return "", tag


def svg_problems(text) -> list:
    """What makes an SVG unfit for a lesson (empty when it may be used): the problems name the element or the attribute."""
    if not isinstance(text, str) or not text.strip():
        return ["svg: empty; send the whole SVG file"]
    out = []
    if len(text.encode("utf-8")) > MAX_BYTES:
        out.append(f"svg: {len(text.encode('utf-8'))} bytes; at most {MAX_BYTES} (fewer points, fewer elements)")
    if re.search(r"<!DOCTYPE|<!ENTITY|<\?xml-stylesheet|<!\[CDATA\[", text, re.IGNORECASE):
        return out + ["svg: no DOCTYPE, ENTITY, stylesheet or CDATA"]
    try:
        root = ET.fromstring(text)
    except ET.ParseError as exc:
        return out + [f"svg: not well-formed XML ({exc})"]
    ns, name = _local(root.tag)
    if ns != SVG_NS or name != "svg":
        return out + [f'svg: the root must be <svg xmlns="{SVG_NS}">, not <{name}>']
    box = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", root.get("viewBox", ""))]
    if len(box) != 4 or box[2] <= 0 or box[3] <= 0:
        out.append('svg: a viewBox of four numbers is needed ("0 0 512 512")')
    elif not 0.8 <= box[2] / box[3] <= 1.25:
        out.append(f"svg: the viewBox {box[2]:g} x {box[3]:g} is not square; an icon is drawn in a square (0 0 512 512)")
    ids, refs, shapes, visible, count = set(), set(), 0, 0, 0
    for el in root.iter():
        count += 1
        ns, tag = _local(el.tag)
        if ns != SVG_NS:
            out.append(f"<{tag}>: an element outside the SVG namespace is not allowed")
            continue
        if tag not in ELEMENTS:
            why = "an icon carries no words; the lesson writes them" if tag in ("text", "tspan", "textPath") else "not allowed in BIE's icons"
            out.append(f"<{tag}>: {why} (allowed: {', '.join(sorted(ELEMENTS))})")
            continue
        if tag in ("title", "desc"):
            continue
        for key, value in el.attrib.items():
            kns, kname = _local(key)
            if kns or kname not in ATTRIBUTES:
                out.append(f"<{tag}> attribute {kname!r}: not allowed (no style, href, event or font attributes)")
                continue
            if BAD_VALUE.search(value):
                out.append(f"<{tag}> {kname}={value[:40]!r}: no link, script or outside reference (only url(#id))")
            refs |= set(URL_REF.findall(value))
        if el.get("id"):
            ids.add(el.get("id"))
        if tag in SHAPES:
            shapes += 1
            fill, stroke = (el.get("fill") or "").strip().lower(), (el.get("stroke") or "").strip().lower()
            if fill not in BLANK or (stroke and stroke not in BLANK):
                visible += 1
        if (el.text or "").strip() and tag not in ("title", "desc"):
            out.append(f"<{tag}>: no words in a drawing")
    if count > MAX_ELEMENTS:
        out.append(f"svg: {count} elements; at most {MAX_ELEMENTS}")
    if shapes < MIN_SHAPES:
        out.append(f"svg: {shapes} shapes; a drawing needs at least {MIN_SHAPES} (path, rect, circle, ellipse, line, polyline, polygon)")
    elif not visible:
        out.append("svg: every shape is blank (no fill and no stroke): the drawing would not show")
    for ref in sorted(refs - ids):
        out.append(f"url(#{ref}): no element has id {ref!r}")
    return out


def clean_svg(text: str) -> str:
    """The SVG as BIE stores it: comments and processing instructions dropped, width and height from the viewBox."""
    ET.register_namespace("", SVG_NS)
    root = ET.fromstring(text)
    box = [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", root.get("viewBox", ""))]
    if len(box) == 4:
        root.set("width", f"{box[2]:g}")
        root.set("height", f"{box[3]:g}")
    return ET.tostring(root, encoding="unicode", short_empty_elements=True)


def wants(need: dict) -> tuple:
    """(True, "") when the coder may draw this need, else (False, why)."""
    thing = str(need.get("thing") or "").strip()
    if need.get("kind") not in ("icon", "image"):
        return False, f"a {need.get('kind')} is for BIE's builders (a world kit, a block, a model), not a drawing"
    if not thing:
        return False, "no thing named"
    if len(thing) > 80:
        return False, "over 80 characters: a description, not one thing"
    if PEOPLE.search(thing):
        return False, "a person is drawn as a generic figure by the blocks, never as a picture of someone (card rule 8)"
    if re.search(r"\b[A-Za-z]*[A-Z][A-Za-z]*\b", thing):
        return False, "a name (a place, a brand, a person or a currency's own sign): Navin's decision, not a drawing"
    if NEVER.search(thing):
        return False, "a map, a flag, a border, a logo or an emblem is never drawn by the coder"
    from ..toolbox import icons
    from . import visual_thinking
    head = icons._head(icons._words(thing))
    if visual_thinking.is_text_thing(thing):       # the lexicon's text_heads: a label, a tag, an amount, a symbol, a mark
        return False, f"a {head} is text or a mark on screen, written by the blocks, not a picture"
    return True, ""


def slug(thing: str) -> str:
    base = re.sub(r"[^a-z0-9]+", "-", thing.lower()).strip("-")[:40] or "thing"
    return f"{base}-{hashlib.sha256(thing.encode('utf-8')).hexdigest()[:6]}"


def words_of(thing: str) -> list:
    return [w for w in re.findall(r"[a-z]+|[ऀ-ॿ]+", thing.lower()) if len(w) > 1 and w not in ("of", "the", "and", "a", "an", "in", "on", "with")]


def in_library(thing: str, library) -> list:
    """The library's pictures OF the thing (``AssetLibrary.pictures_of``: a fetched picture tagged with the whole thing or
    every word of it; a coder drawing only by its own thing, title or head noun, never by a tag alone)."""
    if library is None:
        return []
    return library.pictures_of(thing, every_word=True)


def drawn_as(thing: str, drawn: list) -> str:
    """The thing of this run already drawn that shows ``thing`` too: the same head noun, every word of ``thing`` among its
    words ("merchants": the merchant; "silver piece": the shaped silver piece), or ''. The library finds that drawing for
    ``thing`` by the same rule (``AssetLibrary.pictures_of``), so it is drawn once (seekh -> BIE, the addendum proof's coder
    run: 16 of 150 drawings were another phrasing of a thing drawn in the same run)."""
    from bie.toolbox import icons
    words = [w for w in icons._words(thing) if w not in icons.FIT_STOP]
    head = icons._head(words)
    if not head:
        return ""
    content = {icons._stem(w) for w in words if w not in icons.FIT_PREPS and len(w) > 1}
    for other in drawn:
        theirs = [w for w in icons._words(other) if w not in icons.FIT_STOP]
        their_head = icons._head(theirs)
        if their_head and icons._stem(their_head) == icons._stem(head) and content <= {icons._stem(w) for w in theirs}:
            return other
    return ""


def spec_of(need: dict, course: dict | None = None) -> dict:
    course = course or {}
    where = ", ".join(x for x in (course.get("title"), course.get("subject"), course.get("learners")) if x)
    return {"thing": need["thing"], "for": f"a video lesson ({where})" if where else "a video lesson",
            "shown_in": f"{len(need.get('beats') or [])} beat(s) of part {need.get('part', '')}".strip()}


def _check(value: dict) -> list:
    out = svg_problems(value.get("svg"))
    tags = value.get("tags") or []
    if not isinstance(tags, list) or len(tags) > 8 or any(not isinstance(t, str) or not 0 < len(t) <= 40 for t in tags):
        out.append("tags: up to 8 short words")
    if not 0 < len(str(value.get("name") or "")) <= 60:
        out.append("name: the thing in a few words (up to 60 characters)")
    if not 0 < len(str(value.get("alt") or "")) <= 160:
        out.append("alt: one short line (up to 160 characters) saying what the picture shows")
    return out


def coder_step(need: dict, course: dict | None = None, *, max_rounds: int = 3) -> Step:
    spec = spec_of(need, course)
    user = ("Draw this thing as one SVG icon (the rules are above).\n\n" + json.dumps(spec, ensure_ascii=False, indent=1)
            + "\n\nReply with the JSON (name, svg, tags, alt).")
    return Step(section=SECTION, unit=slug(need["thing"]), instructions_version=VERSION, system=card(), user=user, schema=SCHEMA,
                check=_check, max_rounds=max_rounds)


def made_markdown(made: dict) -> str:
    q = made["quality"]
    lines = ["# BIE's coder · drawings made", "",
             f"{q['made']} of {q['asked']} needs drawn ({q['first_try']} on the first try, {q['rounds']} rounds); "
             f"{q['in_library']} were in the shared library already; {q['skipped']} not for the coder. Each drawing passed BIE's "
             "SVG checks; the fetch workflow (`--made`) checks it again and adds it to the shared library.", "",
             "| Thing | File | Rounds | Status |", "| --- | --- | --- | --- |"]
    for item in made["items"]:
        lines.append(f"| {item['thing']} | {item.get('file') or '—'} | {item['rounds']} | {item['status']} |")
    if made["skipped"]:
        lines += ["", "Not drawn:", ""] + [f"- {s['thing']}: {s['why']}" for s in made["skipped"]]
    return "\n".join(lines) + "\n"


def run_coder(needs: dict, runner, out_dir, *, course: dict | None = None, library=None, limit: int = LIMIT, workers: int = 2,
              max_rounds: int = 3) -> dict:
    """Draw the needs the coder may draw and the library lacks; write made/, made.json and MADE.md. Returns made.json."""
    out = Path(out_dir)
    (out / "made").mkdir(parents=True, exist_ok=True)
    seen, todo, skipped, held = {}, [], [], []
    for need in needs.get("needs") or []:
        key = str(need.get("thing") or "").strip().lower()
        if not key or key in seen:
            if key in seen:
                seen[key]["beats"] = sorted(set(seen[key].get("beats") or []) | set(need.get("beats") or []))
            continue
        seen[key] = dict(need)
        ok, why = wants(need)
        if not ok:
            skipped.append({"thing": need.get("thing", ""), "kind": need.get("kind", ""), "why": why})
        elif in_library(need["thing"], library):
            held.append(need["thing"])
        else:
            todo.append(seen[key])
    todo.sort(key=lambda n: -len(n.get("beats") or []))
    kept = []
    for need in todo:
        other = drawn_as(need["thing"], [k["thing"] for k in kept])
        if other:                                                # not in the library yet: a skipped need, not a held one
            skipped.append({"thing": need["thing"], "kind": need.get("kind", ""),
                            "why": f"shown by this run's drawing of {other!r}"})
        else:
            kept.append(need)
    todo = kept
    for extra in todo[limit:]:
        skipped.append({"thing": extra["thing"], "kind": extra.get("kind", ""), "why": f"over this run's limit of {limit} drawings"})
    todo = todo[:limit]

    def one(need):
        step = coder_step(need, course, max_rounds=max_rounds)
        return need, step, runner.run(step)

    items, today = [], date.today().isoformat()
    with ThreadPoolExecutor(max_workers=max(1, workers)) as pool:
        for need, step, result in pool.map(one, todo):
            item = {"thing": need["thing"], "slug": step.unit, "beats": need.get("beats") or [], "part": need.get("part", ""),
                    "video": need.get("video", ""), "status": result.status, "rounds": len(result.rounds),
                    "first_try": result.passed and len(result.rounds) == 1}
            if result.passed:
                svg = clean_svg(result.output["svg"])
                if svg_problems(svg):                                     # the cleaned file is checked again
                    item.update(status="failed", problems=svg_problems(svg))
                else:
                    (out / "made" / f"{step.unit}.svg").write_text(svg, encoding="utf-8")
                    tags = sorted({need["thing"].lower(), *words_of(need["thing"]),
                                   *(str(t).strip().lower() for t in result.output.get("tags") or [] if str(t).strip())})
                    item.update(file=f"made/{step.unit}.svg", sha256=hashlib.sha256(svg.encode("utf-8")).hexdigest(),
                                name=str(result.output.get("name", ""))[:60], alt=str(result.output.get("alt", ""))[:160],
                                tags=tags, licence=LICENCE, licence_url=LICENCE_URL, source=SOURCE, author=AUTHOR,
                                generated_by=GENERATED_BY, prompt=step.user, generated_on=today)
            items.append(item)
    made = {"schema": formats.tag("coder_made"), "version": VERSION, "rulebook_version": runner.rulebook.version,
            "maker_route": runner.maker, "items": items, "skipped": skipped, "in_library": held,
            "quality": {"asked": len(todo), "made": sum(1 for i in items if i.get("file")),
                        "first_try": sum(1 for i in items if i.get("file") and i["first_try"]),
                        "rounds": sum(i["rounds"] for i in items), "in_library": len(held), "skipped": len(skipped)}}
    formats.check("coder_made", made, where=str(out / "made.json"))
    (out / "made.json").write_text(json.dumps(made, ensure_ascii=False, indent=1), encoding="utf-8")
    (out / "MADE.md").write_text(made_markdown(made), encoding="utf-8")
    return made


def add_made(made: dict, files_base, library, *, read=None) -> dict:
    """The made drawings into a library (the fetch workflow's ``--made``): each file is read (``read(path) -> bytes`` under
    ``files_base``), checked again (it must match its sha256 and pass ``svg_problems``) and added with its provenance."""
    read = read or (lambda p: (Path(files_base) / p).read_bytes())
    added, refused = [], []
    for item in made.get("items") or []:
        if not item.get("file"):
            continue
        try:
            data = read(item["file"])
        except (OSError, ValueError) as exc:
            refused.append({"thing": item["thing"], "why": f"file not read: {type(exc).__name__}"})
            continue
        text = data.decode("utf-8", errors="replace")
        problems = svg_problems(text)
        if hashlib.sha256(data).hexdigest() != item.get("sha256"):
            problems.append("the file does not match its sha256 in made.json")
        if problems:
            refused.append({"thing": item["thing"], "why": "; ".join(problems)[:300]})
            continue
        asset = library.add_bytes(data, mime="image/svg+xml", source=SOURCE, title=item.get("name") or item["thing"],
                                  page_url=str(files_base), licence=item.get("licence", LICENCE),
                                  licence_url=item.get("licence_url", LICENCE_URL), author=AUTHOR, credit="",
                                  tags=item.get("tags") or [item["thing"].lower()], description=item.get("alt", ""),
                                  generated_by=item.get("generated_by", ""), prompt=item.get("prompt", ""),
                                  generated_on=item.get("generated_on", ""))
        added.append({"thing": item["thing"], "asset_id": asset.asset_id})
    return {"added": added, "refused": refused}

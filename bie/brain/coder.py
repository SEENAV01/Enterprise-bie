"""BIE's coder: a picture no source has, drawn as SVG code from a short spec (Task 046 Part D2 addendum, Navin, 2 November 2026).

Navin: "jis cheej ka jikar hai wohi cheej dikhe" — whatever a beat names goes through one general path: the shared library,
the icon index (Twemoji, Font Awesome, Fluent Emoji), the fetch step in GitHub Actions (open sources), and, if still missing,
this coder. Nothing is hand-made for one chapter.

    python tools/run_brain.py --section coder --from-run <canvas run folder or URL with needs.json> [--library <shared library URL>]

For every need of ``needs.json`` (``bie.brain.needs/1``) that the coder may draw (``wants``: an icon or an image of a thing;
never a person, a name, a map, a flag or a logo) and that the shared library does not hold yet, code writes a short spec and
the maker (Codex through the ChatGPT plan on Navin's machine; nothing billed) writes one SVG file. Code checks it
(``svg_problems``: one SVG root with a square viewBox, only the allowed elements and attributes, no script, link, image,
style, font or words, at most 400 elements and 40 KB, a visible drawing) and sends the exact problems back for another round.
A passed drawing is written cleaned (``clean_svg``) to ``made/<slug>.svg`` and listed in ``made.json``
(``bie.brain.coder-made/1``) with its provenance (who drew it, the spec, the date): the fetch workflow
(``tools/task046d_fetch_needs.py --made``) checks it again and adds it to the shared library under the licence policy's
``generated_images`` class (Navin, 29 October 2026: pictures BIE makes through the ChatGPT plan, with their provenance), so
every later book finds it first.
"""

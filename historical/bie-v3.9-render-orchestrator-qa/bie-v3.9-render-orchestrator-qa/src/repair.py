REPAIRABLE={
"TEXT_OVERFLOW":"LAYOUT_RECALCULATION",
"AUDIO_MISSING":"ASSET_RELINK",
"NON_AUDIO_TIMING":"TIMING_RECOMPILE",
"NO_VISUAL_LAYERS":"VISUAL_REPLAN",
"RENDER_FAILED":"RENDER_RETRY"
}

def repair_actions(report):
    return [REPAIRABLE[e] for e in report.get("errors",[]) if e in REPAIRABLE]
